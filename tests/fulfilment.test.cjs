'use strict';
const assert=require('node:assert/strict');
const G=require('../dist/game-core.js');
const F=require('../dist/fulfilment.js');
const speech=require('../audio-corpus.cjs');
const L=require('../dist/interface-language.js');
let checks=0;
const ok=(v,m)=>{checks++;assert.ok(v,m);};
const eq=(a,b,m)=>{checks++;assert.deepEqual(a,b,m);};
for(const grams of [1,5,21,85,100,101,250,500,999,1000,1250,2005,9999,10000]){
  eq(F.weightWords(grams),speech.spokenAmount({measure:'weight'},grams),'Written scale answers agree with audited speech number forms');
  ok(F.weightAnswerMatches(grams,F.weightWords(grams)),'Canonical words accepted');
  ok(!F.weightAnswerMatches(grams,String(grams)),'Digits do not answer the language exercise');
  ok(!F.weightAnswerMatches(grams,F.weightWords(grams+1)),'Different mass rejected');
}
ok(F.weightAnswerMatches(1250,' НЭГ килограмм  хоёр зуун тавин грамм. '),'Case and whitespace tolerated');
ok(F.weightAnswerMatches(1000,'нэг килограм'),'Common kilogram spelling tolerated');
ok(F.weightAnswerMatches(500,'хагас килограмм'),'Half a kilogram accepted');
ok(F.weightAnswerMatches(1250,'мянга хоёр зуун тавин грамм'),'Equivalent grams accepted');
for(const invalid of [-1,1.5,NaN,Infinity,10001])eq(F.weightWords(invalid),'','Invalid mass has no answer');
const campaign=G.createCampaign([50,50,50,50]);
for(const order of campaign){
  const p={bags:F.requiredBags(order),number:String(F.orderNumber(order)),customer:order.customer,transport:F.transportFor(order)};
  ok(F.prepared(order,p),'Every campaign order has an achievable preparation');
  ok(!F.prepared(order,{...p,bags:0}),'Bags required');
  ok(!F.prepared(order,{...p,number:'99999'}),'Wrong order number rejected');
  ok(!F.prepared(order,{...p,customer:'Өөр хүн'}),'Wrong customer rejected');
  ok(!F.prepared(order,{...p,transport:p.transport==='cart'?'basket':'cart'}),'Carrier capacity required');
  eq(F.sanitizePrep(order,p),p,'Prepared state survives serialization');
}
const transportOrder=n=>({id:1,customer:'Ану',lines:[{productId:'eggs',amount:G.BY_ID.eggs.pack*n}]});
eq(F.transportFor(transportOrder(6)),'basket','Six packs fit basket');
eq(F.transportFor(transportOrder(7)),'cart','Seven packs need cart');
eq(F.requiredBags(transportOrder(7)),2,'Seven packs need two bags');
const writtenLabelOrder={number:1,id:77,customer:'Ану',lines:[{productId:'milk',amount:1000}]};
for(const number of ['1','001','№ 1','Заказ № 1','заказ 001','ЗАКАЗ: №001','Захиалга № 001','No. 1','#1','  Заказ\u00a0№\u00a01  ']){
 ok(F.labelMatches(writtenLabelOrder,{number,customer:'Ану'}),'A matching human-written order label is accepted');
 const prep=F.sanitizePrep(writtenLabelOrder,{number,customer:'Ану',bags:1,transport:'basket'});
 ok(F.prepared(writtenLabelOrder,JSON.parse(JSON.stringify(prep))),'A labelled bag stays prepared after save/reload');
}
for(const number of ['Заказ № 2','Заказ № 1 и № 2','1e0','+1','1.0','1 2','Заказ Ану 1','№0','№1000000'])ok(!F.labelMatches(writtenLabelOrder,{number,customer:'Ану'}),'Incorrect or ambiguous order numbers are rejected');
ok(!F.labelMatches(writtenLabelOrder,{number:'Заказ № 1',customer:'Бат'}),'A correct written number never bypasses the customer name check');
const source=campaign.find(o=>o.levelIndex===1);
const order={...source,lines:[{productId:'milk',amount:2000}]};
const inventory=G.createInventory(order),fresh=inventory.find(l=>l.productId==='milk'&&l.pack===1000&&!G.isExpired(l)),expired=inventory.find(l=>l.productId==='milk'&&l.pack===1000&&G.isExpired(l));
ok(fresh&&expired,'Both milk batches present');
const mixed={[fresh.id]:1,[expired.id]:1};
ok(!G.validateOrder(order,inventory,mixed).ok,'Truth detects expired milk');
const unchecked=F.packingCheck(order,inventory,mixed,{});
ok(unchecked.ok&&unchecked.unverified.length===2,'Completeness check allows unchecked dates');
ok(!F.packingCheck(order,inventory,mixed,{[expired.id]:true}).ok,'Known expired milk cannot pass');
eq(F.sanitizeInspections({[expired.id]:true,[fresh.id]:false,unknown:true},inventory),{[expired.id]:true},'Only valid explicitly checked dates persist');
const claims=F.complaintsFor(order,inventory,mixed);
eq(claims.length,1,'Only bad product gets a claim');
eq(claims[0].amount,1000,'Only bad half of milk order gets refunded');
eq(claims[0].refund,4800,'Refund excludes good milk');
eq(F.complaintsFor(order,inventory,{[fresh.id]:2}),[],'Fresh order produces no complaint');
let service={...F.emptyService(),complaints:claims,originalCart:mixed,hadComplaint:true};
ok(F.hasPending(service),'Open claim blocks completion');
let refunded=F.refundComplaint(service,claims[0].id);
eq(F.refundTotal(refunded),4800,'Single item refund recorded');
eq(F.refundComplaint(refunded,claims[0].id),refunded,'Repeated refund has no effect');
ok(!F.hasPending(refunded),'Refund resolves claim');
eq(F.runStars(1,refunded),2,'Complaint caps grade at two stars');
eq(F.runStars(1,F.emptyService()),3,'Fresh first try gets three stars');
let replacing=F.beginReplacement(service,claims[0].id);
eq(F.replacementOrder(order,replacing).lines,[{productId:'milk',amount:1000}],'Replacement only asks for spoiled quantity');
eq(order.lines[0].amount,2000,'Original order and audio contents unchanged');
let failed=F.finishReplacement(replacing,claims[0].id,{[expired.id]:1},false);
ok(F.hasPending(failed)&&!failed.activeId&&failed.complaints[0].attempts===1,'Bad replacement reopens claim');
eq(failed.sentCart[expired.id],1,'Shipped replacement stays out of stock');
replacing=F.beginReplacement(failed,claims[0].id);
const resolved=F.finishReplacement(replacing,claims[0].id,{[fresh.id]:1},true);
ok(!F.hasPending(resolved)&&resolved.complaints[0].status==='replaced','Fresh replacement resolves claim');
eq(F.finishReplacement(resolved,claims[0].id,{[fresh.id]:1},true),resolved,'Cannot ship same replacement twice');
eq(F.sanitizeService(JSON.parse(JSON.stringify(resolved)),order,inventory),resolved,'Resolved state survives reload');
const corrupted=F.sanitizeService({...service,complaints:[{...claims[0],refund:99999999},claims[0],{productId:'fake',amount:1}]},order,inventory);
eq(corrupted.complaints.length,1,'Malformed and duplicated claims discarded');
eq(corrupted.complaints[0].refund,4800,'Saved refund cannot override item price');
for(const text of ['Тохиргоо','Хаах','Захиалга шалгах','Жинлэх','Хугацааг шалгах','Шинэ бараагаар солих'])ok(L.translateText(text)!==text,'Essential Russian controls translated');
eq(Object.keys(L.DEPARTMENTS).length,19,'Every navigation destination, including the three separate freezers, has a Russian hint');
eq(L.translateText(F.weightWords(1250)),F.weightWords(1250),'Mongolian weight answer stays Mongolian');
eq(L.translateText('Хулан'),'Хулан','Customer names stay Mongolian');
eq(L.translateText('Нийт 200 захиалга'),'Всего заказов: 200','Dynamic order count translated');
eq(L.translateText('Тавиурт: 3 савлагаа · Уутанд: 0 савлагаа'),'На полке: 3 уп. · В корзине: 0 уп.','Stock caption is fully Russian');
eq(L.translateText('Ширээ рүү очих →'),'К упаковочному столу →','Action with arrow is translated');
eq(L.translateText('Уутанд 2 савлагаа байна'),'В корзине: 2 уп.','Basket count has no mixed inflection');
const branded=campaign.find(o=>o.preference?.kind==='brand');
const otherLine=branded.lines.find(l=>l.productId!==branded.preference.productId);
const replacement=F.replacementOrder(branded,{activeId:'x',complaints:[{id:'x',productId:otherLine.productId,amount:otherLine.amount}]});
ok(!replacement.preference,'Replacement does not repeat a preference about an unrelated product');
console.log(`PASS: ${checks} preparation, written weight, optional date check, SMS, refund, replacement and localization checks.`);
