const assert = require('node:assert/strict');
const P = require('../dist/profile.js');
const original = {version:2,mode:'campaign',counts:[5,7,13,50],bestById:{'campaign:1':3,'legacy:2':2},drafts:{'campaign:2':{cart:{'o2-l1':2},attempts:1}},activeByMode:{campaign:2,legacy:4}};
const before=JSON.stringify(original), migrated=P.upgrade(original);
assert.equal(JSON.stringify(original),before);
assert.equal(migrated.mode,'classic');
assert.equal(migrated.bestById['classic:1'],3);
assert.equal(migrated.bestById['campaign:1'],undefined);
assert.deepEqual(migrated.drafts['classic:2'],original.drafts['campaign:2']);
assert.deepEqual(migrated.activeByMode,{classic:2,legacy:4});
assert.deepEqual(migrated.counts,original.counts);
assert.equal(migrated.classicAvailable,true);
assert.equal(P.upgrade(migrated).migrated,false);
assert.deepEqual(P.upgrade(migrated).drafts,migrated.drafts);
assert.equal(P.upgrade({...original,mode:'legacy'}).mode,'legacy');
assert.equal(P.upgrade({}).classicAvailable,false);
assert.equal(P.upgrade({}).scaleHints,true,'A new player starts with written-weight hints enabled');
assert.equal(P.upgrade(original).scaleHints,true,'Existing profiles without this preference receive the enabled default');
assert.equal(P.upgrade({scaleHints:false}).scaleHints,false,'An explicit opt-out is preserved');
assert.equal(P.upgrade(JSON.parse(JSON.stringify(P.upgrade({...original,scaleHints:false})))).scaleHints,false,'The opt-out survives migration, JSON saving and reload');
assert.equal(P.upgrade({scaleHints:true}).scaleHints,true,'Hints can be enabled again');
for(const scaleHints of [undefined,null,'false',0])assert.equal(P.upgrade({scaleHints}).scaleHints,true,'Only an explicit boolean false disables hints');
console.log('PASS profile migration: old stars, cart, attempts, selected order and counts stay bound to archived catalogue');
